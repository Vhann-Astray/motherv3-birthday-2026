function loadYouTube(el) {
  const id = el.getAttribute("data-yt");
  if (!/^[A-Za-z0-9_-]{11}$/.test(id)) return;
  el.removeAttribute("data-yt");
  el.removeAttribute("role");
  el.removeAttribute("tabindex");
  el.innerHTML =
    `<iframe src="https://www.youtube-nocookie.com/embed/${id}` +
    `?autoplay=1&rel=0&playsinline=1&color=white" title="YouTube video" ` +
    `frameborder="0" referrerpolicy="strict-origin-when-cross-origin" ` +
    `allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" ` +
    `allowfullscreen></iframe>`;
}

