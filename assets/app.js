/* ---------- Small helpers ---------- */
const $ = (sel) => document.querySelector(sel);
const esc = (s) =>
  String(s).replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c])
  );

// Sentinel tokens emitted by build.py for things that must survive escaping.
// U+FFF9 / U+FFFA are interlinear-annotation controls: never present in real text.
const EMOJI_RE = /￹e\|([^|￺]*)\|([^￺]*)￺/g;
const MENTION_RE = /￹m\|([^￺]*)￺/g;

function renderContent(text) {
  // 1) escape raw text, 2) apply a tiny Discord-flavoured markdown,
  // 3) swap safe sentinel tokens for the only HTML we allow (emoji <img>, mentions).
  let html = esc(text || "")
    .replace(/^&gt; (.*)$/gm, '<span class="quote">$1</span>')
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    .replace(/\*(.+?)\*/g, "<em>$1</em>")
    .replace(/__(.+?)__/g, "<u>$1</u>")
    .replace(/~~(.+?)~~/g, "<s>$1</s>")
    .replace(/`([^`]+)`/g, "<code>$1</code>");

  // Resolved Discord mentions (token) and plain @name typed by hand.
  html = html
    .replace(MENTION_RE, (_, name) => `<span class="mention">@${esc(name)}</span>`)
    .replace(/(^|[^\w@])@(\w+)/g, '$1<span class="mention">@$2</span>');

  // Custom emoji: token -> <img>. Path is generated by build.py (safe, local).
  html = html.replace(
    EMOJI_RE,
    (_, path, name) =>
      `<img class="emoji-c" src="${esc(path)}" alt=":${esc(name)}:">`
  );

  return html;
}

