/* ----- OpenSeadragon branch (only when tiles exist) ----- */
function loadScript(src) {
  return new Promise((resolve, reject) => {
    const s = document.createElement("script");
    s.src = src;
    s.onload = resolve;
    s.onerror = reject;
    document.head.appendChild(s);
  });
}

async function openWithOSD(tileSrc) {
  vImg.style.display = "none";
  osdHost.style.display = "block";
  try {
    if (typeof OpenSeadragon === "undefined") {
      await loadScript(
        "https://cdn.jsdelivr.net/npm/openseadragon@4.1.0/build/openseadragon/openseadragon.min.js"
      );
    }
    osd = OpenSeadragon({
      element: osdHost,
      prefixUrl:
        "https://cdn.jsdelivr.net/npm/openseadragon@4.1.0/build/openseadragon/images/",
      tileSources: tileSrc + (version.magma ? `?v=${version.magma}` : ""),
      showNavigator: true,
      navigatorPosition: "BOTTOM_RIGHT",
      maxZoomPixelRatio: 4, // allow zooming past native pixels
      gestureSettingsMouse: { clickToZoom: false, dblClickToZoom: true },
    });
  } catch {
    // CDN unreachable: fall back to the plain zoom/pan viewer.
    osd = null;
    const s = magmaSources();
    osdHost.style.display = "none";
    vImg.style.display = "block";
    const load = new Image();
    load.onload = () => {
      view.natW = load.naturalWidth;
      view.natH = load.naturalHeight;
      vImg.src = load.src;
      fitImage();
    };
    load.src = s.full;
  }
}

