/* ---------- Data loading ---------- */
async function loadJSON(url, { noStore = false } = {}) {
  const res = await fetch(url, noStore ? { cache: "no-store" } : {});
  if (!res.ok) throw new Error(`${url} -> ${res.status}`);
  return res.json();
}

async function boot() {
  applyConfigText();

  // version.json drives cache-busting and the Magma sources. Optional.
  try {
    version = await loadJSON(CONFIG.versionFile, { noStore: true });
  } catch {
    version = {};
  }

  const v = version.messages ? `?v=${version.messages}` : "";
  try {
    MESSAGES = normalize(await loadJSON(CONFIG.dataFile + v));
  } catch {
    try {
      MESSAGES = normalize(await loadJSON(CONFIG.sampleFile));
      console.info("messages.json not found, showing sample data.");
    } catch {
      MESSAGES = [];
      $("#boot").innerHTML =
        "&gt; MOTHERv3.sys booting... <span style='color:#ff7a7a'>[no data]</span> run tools/build.py";
    }
  }

  setupMagma();
  setupDecor();
  updateStats();
  applyView();
  render();
}

/* ---------- Side decorations (parallax) ---------- */
function setupDecor() {
  const items = version.decor || [];
  if (!items.length) return;

  const layer = document.createElement("div");
  layer.className = "decor-layer";
  layer.setAttribute("aria-hidden", "true");

  const v = version.decorHash ? `?v=${version.decorHash}` : "";
  const sides = { left: [], right: [] };
  items.forEach((it) => (sides[it.side] || sides.left).push(it));

  // Fallback vertical spread per side for items without an explicit top.
  const autoTop = (side, i) => {
    const arr = sides[side];
    return arr.length <= 1 ? 50 : 8 + (84 * i) / (arr.length - 1);
  };

  const parallax = [];
  ["left", "right"].forEach((side) => {
    sides[side].forEach((it, i) => {
      const rotate = it.rotate || 0;
      const slot = document.createElement("div");
      slot.className = "decor-item";
      slot.dataset.side = side;
      slot.style.top = (it.top != null ? it.top : autoTop(side, i)) + "%";
      if (it.width != null) slot.style.width = it.width + "px";
      if (it.inset != null) slot.style[side] = it.inset + "px";
      slot.style.transform = `rotate(${rotate}deg)`;

      const img = document.createElement("img");
      img.className = "decor-img";
      img.src = it.src + v;
      img.alt = "";
      img.loading = "lazy";
      if (it.opacity != null) img.style.opacity = it.opacity;
      img.style.animationDelay = ((i % 5) * 0.7).toFixed(2) + "s";
      slot.appendChild(img);
      layer.appendChild(slot);
      parallax.push({
        el: slot,
        speed: it.speed != null ? it.speed : 0.04 + ((i * 37) % 7) / 100,
        rotate,
      });
    });
  });

  document.body.appendChild(layer);

  if (matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  let ticking = false;
  const update = () => {
    const y = window.scrollY;
    for (const p of parallax) {
      p.el.style.transform = `translateY(${(y * p.speed).toFixed(1)}px) rotate(${p.rotate}deg)`;
    }
    ticking = false;
  };
  window.addEventListener(
    "scroll",
    () => {
      if (!ticking) {
        ticking = true;
        requestAnimationFrame(update);
      }
    },
    { passive: true }
  );
  update();
}

function normalize(data) {
  // Accept either a bare array or the generated { _generated, messages } object.
  const list = Array.isArray(data) ? data : data && data.messages ? data.messages : [];
  return list.filter((m) => m && !m.hidden); // hidden handled by build.py too
}

